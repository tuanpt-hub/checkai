import re
"""Kiểm thử trình duyệt cho quy trình 6 bước: thứ tự bước, đối thủ ở Hồ sơ, link thương hiệu tự nhập + hàng chờ duyệt,
chấm tự động (quy tắc + AI cần duyệt, không ghi đè điểm chuyên viên, chấm lại theo lớp), kế hoạch hành động.
Chạy:  npm run dev:fake   rồi   python3 test/ui-workflow.py"""
import asyncio, os, sys
from playwright.async_api import async_playwright
BASE = os.environ.get("BASE", "http://localhost:3100"); SITE = os.environ.get("SITE", "http://127.0.0.1:3199/")
ok = True
def check(name, cond, extra=""):
    global ok
    print(("  ✓ " if cond else "  ✗ ") + name + ((" – " + str(extra)[:200]) if extra and not cond else "")); ok = ok and bool(cond)
async def saved(pg): await pg.wait_for_function("document.querySelector('#saveState').textContent==='Đã lưu'", timeout=15000)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); ctx = await b.new_context(viewport={"width": 1300, "height": 900}); pg = await ctx.new_page(); errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto(BASE); await pg.wait_for_selector('#login:not([hidden]),#app:not([hidden])')
        if await pg.evaluate("!document.querySelector('#login').hidden"):
            await pg.fill('#lgEmail', 'staff@netspace.vn'); await pg.fill('#lgPass', 'Mat-khau-1'); await pg.click('#lgBtn')
        await pg.wait_for_selector('#app:not([hidden])'); await pg.wait_for_timeout(700)
        await pg.click('#newAudit'); await pg.wait_for_timeout(200); await pg.click('[data-act="seed"]'); await saved(pg)
        order = await pg.evaluate("[...document.querySelectorAll('nav [data-tab]')].map(b=>b.dataset.tab)")
        check("thứ tự 6 bước: Hồ sơ → Dữ kiện → Hỏi AI → Chấm → Kết quả → Cải thiện", order[:6] == ['profile', 'evidence', 'probe', 'score', 'result', 'fix'], order)

        print("Bước 1 – Hồ sơ: đối thủ")
        await pg.click('nav [data-tab="profile"]'); await pg.wait_for_timeout(400)
        await pg.click('[data-act="compAI"]'); await pg.wait_for_function("!busy", timeout=20000); await pg.wait_for_timeout(200)
        check("AI gợi ý đối thủ theo ngành", await pg.query_selector('[data-act="compOk"][data-name="Yeah1"]') is not None)
        await pg.click('[data-act="compOk"][data-name="Yeah1"]'); await pg.wait_for_timeout(200)
        await pg.fill('#compNew', 'Dinos'); await pg.click('[data-act="compAdd"]'); await pg.wait_for_timeout(200)
        check("đã duyệt 2 đối thủ", await pg.evaluate("audits[cur].competitors.filter(c=>c.status==='approved').length") == 2)

        print("Bước 1 – Hồ sơ: link cho thương hiệu tự nhập")
        await saved(pg)
        await pg.click('[data-act="intakeNew"]'); await pg.wait_for_selector('#intakeUrl', timeout=15000)
        link = await pg.inner_text('#intakeUrl'); check("tạo link có token trong phần # của URL, dùng địa chỉ /ho-so công khai", re.search(r'/ho-so#t=[A-Za-z0-9_-]{20,}', link), link)
        brand = await ctx.browser.new_context(viewport={"width": 390, "height": 840}); bp = await brand.new_page()
        bp.on('pageerror', lambda e: errs.append('intake: ' + str(e)))
        await bp.goto(link); await bp.wait_for_selector('#form:not([hidden])', timeout=15000)
        check("form thương hiệu mở được khi chưa đăng nhập, token bị xóa khỏi thanh địa chỉ", '#t=' not in bp.url and await bp.input_value('#f_brand') == 'NetSpace', bp.url)
        check("form không lộ điểm hay audit", 'score' not in (await bp.content()).lower() or 'scores' not in (await bp.content()))
        await bp.fill('#f_oneliner', 'NetSpace là công ty công nghệ và truyền thông số, đối tác công nghệ của kol.gov.vn.')
        await bp.click('[data-ai="competitors"]'); await bp.wait_for_selector('[data-add="METUB"]', timeout=15000)
        await bp.click('[data-add="METUB"]'); await bp.fill('#s_name', 'Chị Lan'); await bp.fill('#s_role', 'Trưởng phòng Marketing')
        await bp.fill('#s_email', 'sai-dinh-dang'); await bp.click('#send'); await bp.wait_for_selector('#msg .err', timeout=5000)
        check("form chặn email sai định dạng", 'Email' in await bp.inner_text('#msg'))
        await bp.fill('#s_email', 'lan@netspace.vn'); await bp.fill('#s_phone', '0912 345 678')
        await bp.click('#send'); await bp.wait_for_selector('#msg .ok', timeout=15000)
        check("thương hiệu gửi thành công", 'Đã gửi' in await bp.inner_text('#msg'))
        await bp.screenshot(path='/tmp/wf_intake_m.png', full_page=False)
        check("hồ sơ audit CHƯA bị đổi trước khi duyệt", 'kol.gov.vn' not in (await pg.evaluate("audits[cur].profile.oneliner")))
        await pg.click('[data-act="intakeRefresh"]'); await pg.wait_for_selector('.sub-box', timeout=15000)
        t = await pg.inner_text('.sub-box'); check("hàng chờ hiện đề xuất kèm người gửi, email và số điện thoại", 'Chị Lan' in t and 'lan@netspace.vn' in t and '0912 345 678' in t and 'Câu định vị' in t and 'METUB' in t, t[:240])
        check("email và số điện thoại bấm được để liên hệ", await pg.query_selector('.sub-box a[href="mailto:lan@netspace.vn"]') is not None and await pg.query_selector('.sub-box a[href="tel:0912345678"]') is not None)
        await pg.uncheck('.sub-box input[data-comp]')
        await pg.click('[data-act="intakeApply"]'); await pg.wait_for_timeout(500)
        check("áp dụng mục đã chọn: định vị cập nhật, đối thủ bỏ chọn thì không thêm", 'kol.gov.vn' in await pg.evaluate("audits[cur].profile.oneliner") and await pg.evaluate("!audits[cur].competitors.some(c=>c.name==='METUB')"))
        await pg.click('[data-act="intakeRevoke"]'); await pg.wait_for_timeout(600)
        await bp.reload(); await bp.wait_for_selector('#state.err', timeout=15000)
        check("thu hồi link: form báo hết hạn", 'hết hạn' in await bp.inner_text('#state'))
        await brand.close()

        print("Bước 2, 3 – Dữ kiện và Hỏi AI")
        await pg.click('nav [data-tab="evidence"]'); await pg.wait_for_timeout(300); await pg.fill('#scanUrl', SITE)
        await pg.click('[data-act="evAll"]'); await pg.wait_for_function("!busy&&audits[cur].scan&&audits[cur].entity&&Object.keys(audits[cur].claimChecks||{}).length>0", timeout=90000)
        check("chạy toàn bộ dữ kiện: quét, Wikidata, claim", True)
        await pg.click('nav [data-tab="probe"]'); await pg.wait_for_timeout(300)
        await pg.click('[data-act="run"][data-g="B"]'); await pg.wait_for_selector('.okbox', timeout=60000)

        print("Bước 4 – Chấm 6 lớp")
        await pg.click('nav [data-tab="score"]'); await pg.wait_for_timeout(300)
        manual_before = await pg.evaluate("Object.entries(audits[cur].scores).filter(([k,v])=>v&&v.s!=null&&(!v.src||v.src==='manual')).map(([k,v])=>k+':'+v.s).sort().join(',')")
        await pg.click('[data-act="autoAll"]'); await pg.wait_for_function("!busy", timeout=60000); await pg.wait_for_timeout(300)
        k = await pg.evaluate("scoreCounts(audits[cur])")
        check("có điểm tự động theo quy tắc và điểm AI cần duyệt", k['auto'] > 0 and k['aiPending'] > 0, k)
        check("điểm chuyên viên chấm tay không bị ghi đè", manual_before == await pg.evaluate("Object.entries(audits[cur].scores).filter(([k,v])=>v&&v.s!=null&&(!v.src||v.src==='manual')).map(([k,v])=>k+':'+v.s).sort().join(',')"))
        check("tiêu chí thiếu dữ kiện được đánh dấu, không bịa điểm", k['missing'] > 0, k)
        check("không còn tiêu chí chưa xử lý ngoài nhóm thiếu dữ kiện", k['none'] == 0, k)
        check("nhãn 'AI · cần duyệt' hiển thị", await pg.evaluate("document.querySelector('#view').textContent.includes('AI · cần duyệt')"))
        await pg.click('details[data-layer="5"] summary'); await pg.wait_for_timeout(200)
        before = await pg.evaluate("scoreCounts(audits[cur]).aiPending")
        await pg.click('details[data-layer="5"] [data-act="approve"]'); await pg.wait_for_timeout(200)
        check("duyệt một điểm AI", await pg.evaluate("scoreCounts(audits[cur]).aiPending") == before - 1)
        await pg.click('details[data-layer="5"] [data-act="rescore"]'); await pg.wait_for_function("!busy", timeout=30000); await pg.wait_for_timeout(300)
        check("chấm lại riêng lớp 5", 'AI chấm' in await pg.inner_text('.okbox'))
        await pg.click('nav [data-tab="result"]'); await pg.wait_for_timeout(300)
        check("Kết quả nhắc điểm AI đang chờ duyệt", 'chờ chuyên viên duyệt' in await pg.inner_text('#view'))
        await pg.click('nav [data-tab="score"]'); await pg.wait_for_timeout(300); await pg.click('[data-act="approveAll"]'); await pg.wait_for_timeout(300)
        check("duyệt tất cả điểm AI", await pg.evaluate("scoreCounts(audits[cur]).aiPending") == 0)

        print("Bước 6 – Công cụ cải thiện")
        await pg.click('nav [data-tab="fix"]'); await pg.wait_for_timeout(300)
        await pg.click('[data-act="plan"]'); await pg.wait_for_function("!busy", timeout=30000); await pg.wait_for_timeout(300)
        check("AI soạn kế hoạch hành động theo khung thời gian", await pg.evaluate("document.querySelectorAll('.plan-card').length") >= 2 and '0–30 ngày' in await pg.inner_text('#view'))
        await pg.click('nav [data-tab="result"]'); await pg.wait_for_timeout(300); await pg.click('[data-act="showmd"]')
        check("báo cáo có kế hoạch hành động", 'Kế hoạch hành động' in await pg.inner_text('#mdBox'))
        await saved(pg)
        srv = await pg.evaluate("fetch('/api/audits/'+cur,{headers:{'X-ABR':'1'}}).then(r=>r.json()).then(j=>({plan:(j.audit.plan||{}).items?.length||0,ai:Object.values(j.audit.scores).filter(x=>x.src==='ai').length,comps:(j.audit.competitors||[]).length}))")
        check("kế hoạch, điểm AI và đối thủ được lưu lên máy chủ", srv['plan'] >= 2 and srv['ai'] > 0 and srv['comps'] >= 2, srv)
        m = await ctx.new_page(); await m.set_viewport_size({"width": 380, "height": 800}); await m.goto(BASE); await m.wait_for_selector('#app:not([hidden])'); await m.wait_for_timeout(700)
        over = {}
        for tb in ['profile', 'evidence', 'score', 'fix']:
            await m.evaluate(f"tab='{tb}';renderAll()"); await m.wait_for_timeout(300)
            over[tb] = await m.evaluate("document.documentElement.scrollWidth>document.documentElement.clientWidth+1")
        check("điện thoại: không tràn ngang ở Hồ sơ, Dữ kiện, Chấm, Cải thiện", not any(over.values()), over)
        await pg.click('nav [data-tab="profile"]'); await pg.wait_for_timeout(300); await pg.screenshot(path='/tmp/wf_profile.png', full_page=True)
        await pg.click('nav [data-tab="score"]'); await pg.wait_for_timeout(300); await pg.screenshot(path='/tmp/wf_score.png', full_page=False)
        await pg.click('nav [data-tab="fix"]'); await pg.wait_for_timeout(300); await pg.screenshot(path='/tmp/wf_fix.png', full_page=False)
        check("không có lỗi JavaScript", not errs, errs)
        await b.close()
    print("\nTẤT CẢ ĐẠT" if ok else "\nCÓ LỖI"); sys.exit(0 if ok else 1)
asyncio.run(main())
